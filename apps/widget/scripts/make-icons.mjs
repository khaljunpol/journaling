// Builds src/widgets/icons.ts from lucide (ISC licence), the icon set the web app uses.
// RemoteViews widgets can only draw SVG strings, so the icon shapes are copied in. Run: node scripts/make-icons.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { Resvg } from '@resvg/resvg-js';

const WANTED = {
  gym: 'dumbbell', hiit: 'flame', bodyweight: 'biceps-flexed', climb: 'mountain', run: 'footprints', swim: 'waves',
  bike: 'bike', yoga: 'person-standing', beer: 'beer', wine: 'wine', smoke: 'cigarette', coffee: 'coffee',
  water: 'glass-water', shake: 'milk', pill: 'pill', read: 'book-open', meditate: 'brain', music: 'music',
  write: 'pen-line', games: 'gamepad-2', heart: 'heart',
  smile: 'smile', scale: 'scale', clock: 'clock', more: 'ellipsis', overview: 'layout-grid', trends: 'chart-line', today: 'calendar-check',
};

async function markup(name) {
  const file = new URL(`../../../node_modules/lucide-react/dist/esm/icons/${name}.mjs`, import.meta.url);
  // Renamed icons are one-line re-exports of the new file.
  const alias = readFileSync(file, 'utf8').match(/export \{ default \} from '\.\/([^']+)\.mjs'/);
  if (alias) return markup(alias[1]);
  const { __iconData } = await import(file.href);
  return __iconData.node.map(([tag, attrs]) => {
    const a = Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ');
    return `<${tag} ${a}/>`;
  }).join('');
}

const shapes = {};
for (const [k, v] of Object.entries(WANTED)) shapes[k] = await markup(v);
// Lucide has no racket; same shape as the one the web app used.
shapes.racket = '<ellipse cx="14.5" cy="9.5" rx="5.5" ry="6.5" transform="rotate(45 14.5 9.5)"/><path d="M10.5 13.5 4 20"/><circle cx="19" cy="19" r="1.5"/>';

const out = `// Generated by scripts/make-icons.mjs from lucide (ISC). Do not edit by hand.
export const ICONS = ${JSON.stringify(shapes, null, 2)} as const;

export type IconName = keyof typeof ICONS;

/** One icon as an SVG string, for SvgWidget and SvgXml. */
export function iconSvg(name: IconName, color: string, size: number): string {
  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="\${color}" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">\${ICONS[name]}</svg>\`;
}
`;
writeFileSync(new URL('../src/widgets/icons.ts', import.meta.url), out);

// The app's windows use white PNGs tinted with Image tintColor: no native SVG library, whose
// generated paths break the Windows build.
mkdirSync(new URL('../assets/icons/', import.meta.url), { recursive: true });
for (const [name, body] of Object.entries(shapes)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#ffffff" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: 96 } }).render().asPng();
  writeFileSync(new URL(`../assets/icons/${name}.png`, import.meta.url), png);
}
const map = Object.keys(shapes).map((n) => `  ${JSON.stringify(n)}: require('../../assets/icons/${n}.png'),`).join('\n');
writeFileSync(new URL('../src/widgets/iconImages.ts', import.meta.url), `// Generated by scripts/make-icons.mjs. Do not edit by hand.
import type { ImageSourcePropType } from 'react-native';
import type { IconName } from './icons';

export const ICON_IMAGES: Record<IconName, ImageSourcePropType> = {
${map}
};
`);
console.log(Object.keys(shapes).length, 'icons');
